// Global active language getter
function getActiveLanguage() {
  const cached = localStorage.getItem("vosme_lang");
  if (cached && translations[cached]) {
    return cached;
  }
  
  // Default browser agent fallback
  const browserLang = navigator.language ? navigator.language.split("-")[0] : "en";
  if (translations[browserLang]) {
    return browserLang;
  }
  
  return "en"; // Default absolute fallback
}

// Global page translation runner
function translatePage(lang = "en") {
  const dict = translations[lang];
  if (!dict) return;

  // 1. Translate inner contents
  const translatableElements = document.querySelectorAll("[data-i18n]");
  translatableElements.forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) {
      el.innerHTML = dict[key];
    }
  });

  // 2. Translate placeholders (mainly form inputs)
  const placeholderElements = document.querySelectorAll("[data-i18n-placeholder]");
  placeholderElements.forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict[key] !== undefined) {
      el.setAttribute("placeholder", dict[key]);
    }
  });

  // 3. Update active HTML language tag for accessibility / crawlers
  document.documentElement.setAttribute("lang", lang === "zh" ? "zh-Hans" : lang);

  // 4. Update the current page's metadata title
  updateMetaTitle(lang);
}

// Manage dynamic title mapping across localized pages
function updateMetaTitle(lang) {
  const currentPath = window.location.pathname;
  const isAbout = currentPath.includes("about.html");
  const isProf = currentPath.includes("professionals.html");
  const isContact = currentPath.includes("contact.html");

  let baseTitle = "";
  if (isAbout) {
    if (lang === "zh") baseTitle = "关于我们 | 始创于2014年的人工智能先驱 | Vosme International Sdn Bhd";
    else if (lang === "ms") baseTitle = "Mengenai Kami | Peneraju AI Sejak 2014 | Vosme International Sdn Bhd";
    else baseTitle = "About Us | Vosme International Sdn Bhd | AI Pioneers Since 2014";
  } else if (isProf) {
    if (lang === "zh") baseTitle = "专业技术服务与架构矩阵 | Vosme International Sdn Bhd";
    else if (lang === "ms") baseTitle = "Perkhidmatan Profesional & Timbunan Teknologi | Vosme International Sdn Bhd";
    else baseTitle = "Our Professional Services & Tech Stack | Vosme International Sdn Bhd";
  } else if (isContact) {
    if (lang === "zh") baseTitle = "联系我们 | 与人工智能与软件定制专家沟通 | Vosme International Sdn Bhd";
    else if (lang === "ms") baseTitle = "Hubungi Kami | Hubungi Pakar Kejuruteraan | Vosme International Sdn Bhd";
    else baseTitle = "Contact Us | Vosme International Sdn Bhd | Get In Touch";
  } else {
    // Default Home
    if (lang === "zh") baseTitle = "Vosme International Sdn Bhd | 领先的人工智能决策咨询、流程自动化与定制开发商";
    else if (lang === "ms") baseTitle = "Vosme International Sdn Bhd | Rundingan AI, Automasi & Aplikasi Tersuai";
    else baseTitle = "Vosme International Sdn Bhd | Premier AI Consulting, Automation & Custom Web Apps";
  }

  document.title = baseTitle;
}

// Central Switch controller
function setLanguage(lang) {
  if (!translations[lang]) return;
  
  // Save preference
  localStorage.setItem("vosme_lang", lang);
  
  // Apply changes
  translatePage(lang);
  
  // Sync the dropdown trigger label
  const labelMap = { en: "EN", zh: "中", ms: "MS" };
  const currentTextSpan = document.querySelector("#lang-btn-current span");
  if (currentTextSpan) {
    currentTextSpan.textContent = labelMap[lang];
  }

  // Sync active visual highlights in dropdown options
  const optionButtons = document.querySelectorAll(".lang-option");
  optionButtons.forEach(btn => {
    if (btn.getAttribute("data-lang") === lang) {
      btn.classList.add("active");
    } else {
      btn.classList.remove("active");
    }
  });
}

// Setup Event Listeners on DOM load
document.addEventListener("DOMContentLoaded", () => {
  const activeLang = getActiveLanguage();
  
  // Perform initial translation
  setLanguage(activeLang);

  // Selector controls hooks
  const trigger = document.getElementById("lang-btn-current");
  const dropdown = document.getElementById("lang-switcher-menu");

  if (trigger && dropdown) {
    // 1. Toggle visibility on trigger click
    trigger.addEventListener("click", (e) => {
      e.stopPropagation();
      const isExpanded = trigger.getAttribute("aria-expanded") === "true";
      trigger.setAttribute("aria-expanded", !isExpanded);
      dropdown.classList.toggle("active");
      trigger.classList.toggle("chevron-rotate");
    });

    // 2. Select option and change language
    const optionButtons = document.querySelectorAll(".lang-option");
    optionButtons.forEach(btn => {
      btn.addEventListener("click", () => {
        const targetLang = btn.getAttribute("data-lang");
        setLanguage(targetLang);
        
        // Collapse menu
        trigger.setAttribute("aria-expanded", "false");
        dropdown.classList.remove("active");
        trigger.classList.remove("chevron-rotate");
      });
    });

    // 3. Close on outside click
    document.addEventListener("click", () => {
      trigger.setAttribute("aria-expanded", "false");
      dropdown.classList.remove("active");
      trigger.classList.remove("chevron-rotate");
    });
  }
});
